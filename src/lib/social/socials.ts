const SERVICE_MAP = SERVICES.reduce<Record<string, SocialService>>((acc, svc) => {
  acc[svc.key] = svc;
  return acc;
}, {});

export function isSocialKey(value: string): value is SocialKey {
  return value in SERVICE_MAP;
}

export function getService(key: string): SocialService | undefined {
  return SERVICE_MAP[key];
}

export function normalizeHandle(service: SocialKey, raw: string): string {
  let v = (raw ?? "").trim();
  if (v.startsWith("@")) v = v.slice(1);
  const strip = service === "discord" ? /[^A-Za-z0-9_.#-]/g : /[^A-Za-z0-9_.-]/g;
  return v.replace(strip, "").slice(0, HANDLE_MAX);
}

export function isValidHandle(service: SocialKey, raw: string): boolean {
  return normalizeHandle(service, raw).length > 0;
}

export function resolveUrl(service: SocialKey, value: string): string | null {
  const svc = SERVICE_MAP[service];
  if (!svc?.urlTemplate) return null;
  const handle = normalizeHandle(service, value);
  if (!handle) return null;
  const url = svc.urlTemplate.replace("{v}", encodeURIComponent(handle));
  return url.startsWith("https://") ? url : null;
}

function brandLuminance(hex: string): number | null {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex);
  if (!m) return null;
  const n = parseInt(m[1], 16);
  const r = (n >> 16) & 255;
  const g = (n >> 8) & 255;
  const b = n & 255;
  return (0.299 * r + 0.587 * g + 0.114 * b) / 255;
}

export function iconColor(service: SocialKey): string | null {
  const svc = SERVICE_MAP[service];
  if (!svc) return null;
  const lum = brandLuminance(svc.brand);
  if (lum == null) return null;
  return lum < 0.22 ? null : svc.brand;
}

export function SocialIcon({
  service,
  size = 18,
  className,
}: {
  service: SocialKey;
  size?: number;
  className?: string;
}): ReactElement | null {
  const svc = SERVICE_MAP[service];
  if (!svc) return null;
  return createElement(
    "svg",
    {
      width: size,
      height: size,
      viewBox: "0 0 24 24",
      fill: "currentColor",
      "aria-hidden": true,
      className,
    },
    createElement("path", { d: svc.iconPath }),
  );
}
